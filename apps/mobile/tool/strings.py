def braces(text):
    # Names used as {name} outside plural syntax must be declared.
    return set(re.findall(r'(?<![\w=])\{([A-Za-z_]\w*)\}', text)) | set(re.findall(r'\{([A-Za-z_]\w*), plural', text))


