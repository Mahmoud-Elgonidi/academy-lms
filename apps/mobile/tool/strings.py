def plurals(text):
    """Each `{x, plural, ...}` in [text]: the name and its branches as one string."""
    for m in re.finditer(r'\{(\w+), plural,', text):
        depth, i = 1, m.end()
        while depth and i < len(text):
            depth += {'{': 1, '}': -1}.get(text[i], 0)
            i += 1
        yield m.group(1), text[m.end():i - 1]


