def braces(text):
    # Names used as {name} outside plural syntax must be declared.
    return set(re.findall(r'(?<![\w=])\{([A-Za-z_]\w*)\}', text)) | set(re.findall(r'\{([A-Za-z_]\w*), plural', text))


for lang in ('ar', 'en'):
    doc = {'@@locale': lang}
    for key, ar, en, ph in S:
        text = ar if lang == 'ar' else en
        missing = braces(text) - set(ph)
        assert not missing, (key, lang, missing)
        doc[key] = text
        if lang == 'ar' and ph:
            doc['@' + key] = {'placeholders': {n: {'type': t} for n, t in ph.items()}}
    with open(os.path.join(out, f'app_{lang}.arb'), 'w', encoding='utf-8') as f:
        json.dump(doc, f, ensure_ascii=False, indent=2)
